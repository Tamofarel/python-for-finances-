import { useEffect, useState } from "react";
import { api } from "../../api/client";
import type { Artifact, ChangeProposal } from "../../api/types";
import { CopyButton, Markdown } from "../../components/Markdown";
import { Field, Modal, Notice, formatTime } from "../../components/ui";
import { ChangeReview } from "./ChangeReview";
import { KIND_LABELS } from "./kinds";

/** View, edit, copy, export or delete one artifact. */
export function ArtifactEditor({ artifact, onSaved, onDeleted }: { artifact: Artifact; onSaved: (a: Artifact) => void; onDeleted: () => void }) {
  const [editing, setEditing] = useState(false);
  const [title, setTitle] = useState(artifact.title);
  const [content, setContent] = useState(artifact.content);
  const [error, setError] = useState<string | null>(null);
  const [exporting, setExporting] = useState(false);
  const [exportPath, setExportPath] = useState("");
  const [proposal, setProposal] = useState<ChangeProposal | null>(null);
  const [confirmDelete, setConfirmDelete] = useState(false);

  useEffect(() => {
    setTitle(artifact.title);
    setContent(artifact.content);
    setEditing(false);
    setProposal(null);
    setExportPath(`docs/${artifact.kind.replace(/_/g, "-")}-${artifact.id}.md`);
  }, [artifact]);

  async function save() {
    setError(null);
    try {
      onSaved(await api.artifacts.update(artifact.project_id, artifact.id, { title, content }));
      setEditing(false);
    } catch (e) {
      setError((e as Error).message);
    }
  }

  return (
    <article className="artifact">
      <header className="artifact-head">
        {editing ? (
          <input className="title-input" value={title} onChange={(e) => setTitle(e.target.value)} aria-label="Artifact title" />
        ) : (
          <h2>{artifact.title}</h2>
        )}
        <p className="small muted">
          {KIND_LABELS[artifact.kind]}, {artifact.created_by === "ai" ? "generated by NOVA" : "written by you"}, updated {formatTime(artifact.updated_at)}
        </p>
        <div className="row">
          {editing ? (
            <>
              <button type="button" className="btn btn-primary btn-sm" onClick={save}>Save artifact</button>
              <button type="button" className="btn btn-sm" onClick={() => { setEditing(false); setTitle(artifact.title); setContent(artifact.content); }}>Cancel</button>
            </>
          ) : (
            <>
              <button type="button" className="btn btn-sm" onClick={() => setEditing(true)}>Edit</button>
              <CopyButton text={artifact.content} label="Copy Markdown" />
              <button type="button" className="btn btn-sm" onClick={() => setExporting(true)}>Save to workspace…</button>
              <button type="button" className="btn btn-ghost btn-sm danger-text" onClick={() => setConfirmDelete(true)}>Delete</button>
            </>
          )}
        </div>
      </header>
      {error && <Notice>{error}</Notice>}
      {proposal && (
        <div className="top-gap">
          <ChangeReview change={proposal} onUpdated={setProposal} />
        </div>
      )}
      {editing ? (
        <textarea className="code-editor tall" value={content} onChange={(e) => setContent(e.target.value)} aria-label="Artifact content (Markdown)" />
      ) : (
        <Markdown>{artifact.content || "_Empty artifact._"}</Markdown>
      )}
      {artifact.source_input && !editing && (
        <details className="top-gap">
          <summary>Original input</summary>
          <p className="pre-wrap small">{artifact.source_input}</p>
        </details>
      )}
      {exporting && (
        <Modal title="Save artifact to workspace" onClose={() => setExporting(false)} footer={
          <>
            <button type="button" className="btn" onClick={() => setExporting(false)}>Cancel</button>
            <button type="button" className="btn btn-primary" onClick={async () => {
              try {
                setProposal(await api.artifacts.exportToFile(artifact.project_id, artifact.id, exportPath));
                setExporting(false);
              } catch (e) {
                setError((e as Error).message);
                setExporting(false);
              }
            }}>Create proposal</button>
          </>
        }>
          <Field label="File path in the workspace" hint="NOVA creates a change proposal. You review and apply it like any other change.">
            <input value={exportPath} onChange={(e) => setExportPath(e.target.value)} />
          </Field>
        </Modal>
      )}
      {confirmDelete && (
        <Modal title="Delete artifact?" onClose={() => setConfirmDelete(false)} footer={
          <>
            <button type="button" className="btn" onClick={() => setConfirmDelete(false)}>Keep it</button>
            <button type="button" className="btn btn-danger" onClick={async () => {
              try { await api.artifacts.remove(artifact.project_id, artifact.id); onDeleted(); } catch (e) { setError((e as Error).message); }
              setConfirmDelete(false);
            }}>Delete artifact</button>
          </>
        }>
          <p>“{artifact.title}” will be deleted from NOVA. Files you already saved to the workspace are not affected.</p>
        </Modal>
      )}
    </article>
  );
}
