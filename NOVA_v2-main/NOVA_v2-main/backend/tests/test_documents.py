def test_content_parsing():
    blocks = parse_blocks("# Title\nfirst line\nsame paragraph\n\n- a\n* b\n1. one\n2) two\n| h1 | h2 |\n|---|---|\n| c1 | c2 |")
    assert blocks == [("heading", (1, "Title")), ("paragraph", "first line same paragraph"), ("bullet", "a"),
                      ("bullet", "b"), ("number", "one"), ("number", "two"), ("table", [["h1", "h2"], ["c1", "c2"]])]
    assert parse_blocks("  \n\n") == []
