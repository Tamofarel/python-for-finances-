@pytest.mark.parametrize("name", ["..\\secret", "../up", "C:\\Windows\\x", "a/b", "con", "..", "x?y", ".hidden"])
def test_file_names_cannot_leave_the_document_folder(tmp_path, name):
    assert clean_filename(name) is None
    adapter, _ = word(tmp_path)
    for arguments in ({"action": "create", "content": "x", "filename": name, "open_in_word": False},
                      {"action": "read", "filename": name}, {"action": "open", "filename": name}):
        result = registry(adapter).execute("word_document", arguments, ctx())
        assert result.status == "denied" and result.data["reason"] == "path_rejected", arguments
    assert not (tmp_path / "NOVA").exists() or list((tmp_path / "NOVA").iterdir()) == []


def test_schema_and_risk_classes(tmp_path):
    adapter, _ = word(tmp_path)
    reg = registry(adapter)
    assert reg.execute("word_document", {"action": "create"}, ctx()).data["reason"] == "invalid_arguments"
    assert reg.execute("word_document", {"action": "open"}, ctx()).data["reason"] == "invalid_arguments"
    assert reg.execute("word_document", {"action": "write", "content": "Hello", "title": "null",
                                         "open_in_word": False}, ctx()).status == "succeeded"  # alias, "null" ignored
    assert reg.permission_for("word_document", {"action": "status"}).value == "read"
    assert reg.permission_for("word_document", {"action": "create", "content": "x"}).value == "routine"
    assert reg.permission_for("word_document", {"action": "create", "content": "x", "if_exists": "replace"}).value == "approval"
    stopped = reg.execute("word_document", {"action": "create", "content": "x"}, ToolContext(paused=True))
    assert stopped.status == "denied" and stopped.data["reason"] == "paused"  # the emergency stop applies


