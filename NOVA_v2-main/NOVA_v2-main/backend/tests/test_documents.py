def test_permission_error_while_saving_is_reported_and_leaves_no_partial_file(tmp_path, monkeypatch):
    adapter, _ = word(tmp_path)

    def denied(*_args, **_kwargs):
        raise PermissionError(13, "Access is denied")

    monkeypatch.setattr(documents.os, "link", denied)
    result = registry(adapter).execute("word_document", {"action": "create", "title": "Daily report", "content": REPORT,
                                                         "open_in_word": False}, ctx())
    assert result.status == "failed" and result.data["blocker"] == "access_denied"
    assert "denied access" in result.message and list((tmp_path / "NOVA").iterdir()) == []


