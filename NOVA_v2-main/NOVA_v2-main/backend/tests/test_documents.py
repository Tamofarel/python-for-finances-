"""Word documents: real .docx files in a temporary folder, with Windows and Word replaced by fakes.

These prove NOVA's own logic: what is written, where, that nothing is overwritten, and that a result is only reported
after the saved file was read back. They do not prove that a real Word installation shows the document; see
docs/ACTIONS.md for the live check.
"""

from __future__ import annotations

import time
from pathlib import Path

import pytest
from docx import Document

from app.tools import documents
from app.tools.documents import WordDocuments, clean_filename, document_tools, parse_blocks
from app.tools.registry import ToolContext, ToolRegistry

REPORT = """Generated by NOVA.

## Summary
- 2 requests
- 1 action **done**

## Steps
1. Open Spotify
2. Play the track

| Time | Request | Result |
|---|---|---|
| 14:18 | play Fast | Done, verified |
"""


class FakeWindows:
    """Stands in for Windows: which processes run, which windows exist, and what opening a file does."""

    def __init__(self, *, installed=True, running=False, shows=True, launch_ok=True, windows=()):
        self.installed, self.shows, self.launch_ok = installed, shows, launch_ok
        self.procs = {"winword.exe"} if running else set()
        self.titles = list(windows)
        self.launched: list[str] = []

    def launch(self, target: str) -> bool:
        self.launched.append(target)
        if self.launch_ok and self.shows:
            self.procs.add("winword.exe")
            self.titles.append(f"{Path(target).stem} - Word")
        return self.launch_ok

    def processes(self) -> set[str]:
        return set(self.procs)

    def windows(self) -> list[str]:
        return ["Spotify Premium", *self.titles]

    def resolve(self, target, _name, _aliases):
        return (target, "path", None) if self.installed else (None, "not_found", "not installed")


def word(tmp_path, fake: FakeWindows | None = None) -> tuple[WordDocuments, FakeWindows]:
    fake = fake or FakeWindows()
    return WordDocuments(tmp_path / "NOVA", launcher=fake.launch, processes=fake.processes, windows=fake.windows,
                         resolver=fake.resolve, poll_interval=0.01), fake


def registry(adapter: WordDocuments, enabled=True) -> ToolRegistry:
    return ToolRegistry(document_tools(enabled, adapter))


def ctx(seconds: float = 5) -> ToolContext:
    return ToolContext(deadline=time.monotonic() + seconds)


@pytest.fixture(autouse=True)
def windows(monkeypatch):
    monkeypatch.setattr("app.tools.documents.sys.platform", "win32")


def test_create_writes_formats_saves_and_verifies_the_document(tmp_path):
    adapter, fake = word(tmp_path)
    result = registry(adapter).execute("word_document", {"action": "create", "title": "Daily report",
                                                         "content": REPORT, "open_in_word": False}, ctx())
    assert result.status == "succeeded", result.message
    path = Path(result.data["path"])
    assert path == tmp_path / "NOVA" / "Daily report.docx" and path.is_file()
    assert result.data["verified"] is True and result.data["missing"] == 0
    assert str(tmp_path / "NOVA") in result.message and "Daily report.docx" in result.message
    assert fake.launched == []  # open_in_word was off: nothing was started

    saved = Document(str(path))
    styles = [(p.style.name, p.text) for p in saved.paragraphs if p.text]
    assert styles[0] == ("Title", "Daily report")
    assert ("Heading 2", "Summary") in styles and ("Heading 2", "Steps") in styles
    assert ("List Bullet", "2 requests") in styles and ("List Number", "Open Spotify") in styles
    assert ("Normal", "Generated by NOVA.") in styles
    bold = [run.text for p in saved.paragraphs for run in p.runs if run.bold]
    assert bold == ["done"]  # **done** became bold text, without the markers
    table = saved.tables[0]
    assert [c.text for c in table.rows[0].cells] == ["Time", "Request", "Result"]
    assert [c.text for c in table.rows[1].cells] == ["14:18", "play Fast", "Done, verified"]
    assert table.rows[0].cells[0].paragraphs[0].runs[0].bold is True
    assert not list((tmp_path / "NOVA").glob("*.tmp"))


def test_reading_back_returns_the_saved_text_in_order(tmp_path):
    adapter, _ = word(tmp_path)
    reg = registry(adapter)
    reg.execute("word_document", {"action": "create", "title": "Daily report", "content": REPORT, "open_in_word": False}, ctx())
    read = reg.execute("word_document", {"action": "read", "filename": "Daily report.docx"}, ctx())
    assert read.status == "succeeded" and read.data["verified"] is True
    lines = read.data["text"].splitlines()
    assert lines[:3] == ["Daily report", "Generated by NOVA.", "Summary"]
    assert "14:18 | play Fast | Done, verified" in lines
    missing = reg.execute("word_document", {"action": "read", "filename": "Nope"}, ctx())
    assert missing.status == "unavailable" and missing.data["blocker"] == "not_found"


