"""A factual record of what the owner asked NOVA and what NOVA did, taken from stored conversations and action
results. Nothing here is written by a model: the report is NOVA's own records, including what failed.
"""

from __future__ import annotations

from collections.abc import Callable
from datetime import UTC, datetime
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import Conversation, Message
from app.tools.registry import PermissionLevel, Tool, ToolContext, ToolInput

MAX_ENTRIES = 60
_RESULT = {"succeeded": "Done", "unverified": "Not confirmed", "needs_input": "Needed a choice",
           "needs_authorization": "Needed a connection", "awaiting_approval": "Waiting for approval",
           "unavailable": "Unavailable", "denied": "Refused", "failed": "Failed", "timed_out": "Timed out",
           "cancelled": "Stopped"}


def _cell(text: str, limit: int) -> str:
    text = " ".join(str(text).replace("|", "/").split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _describe(action: dict[str, Any]) -> str:
    arguments = {k: v for k, v in (action.get("arguments") or {}).items() if k != "content" and v not in (None, "")}
    detail = ", ".join(str(v) for v in arguments.values())
    return _cell(f"{action.get('tool')}: {detail}" if detail else str(action.get("tool")), 90)


def _result(action: dict[str, Any]) -> str:
    label = _RESULT.get(str(action.get("status")), str(action.get("status")))
    if action.get("status") == "succeeded" and action.get("verified"):
        label = "Done, verified"
    return _cell(f"{label}. {action.get('message') or ''}", 170)


def today_activity(db: Session, owner_id: int, *, now: datetime | None = None) -> dict[str, Any]:
    """Today's requests and actions (the owner's local day), oldest first, with a ready-to-write report."""
    now = (now or datetime.now().astimezone())
    start = now.replace(hour=0, minute=0, second=0, microsecond=0)
    rows = db.execute(
        select(Message, Conversation.title)
        .join(Conversation, Conversation.id == Message.conversation_id)
        .where(Conversation.owner_id == owner_id, Message.created_at >= start.astimezone(UTC))
        .order_by(Message.conversation_id, Message.id)
    ).all()
    entries: list[dict[str, Any]] = []
    current: dict[int, dict[str, Any]] = {}
    for message, title in rows:
        if message.role == "user":
            entry = {"at": message.created_at, "conversation": title, "request": message.content, "actions": [],
                     "answered": False, "pending": False}
            current[message.conversation_id] = entry
            entries.append(entry)
            continue
        entry = current.get(message.conversation_id)
        if entry is None:
            continue
        if message.status == "streaming":
            entry["pending"] = True  # the request being answered right now is not part of the record yet
            continue
        entry["answered"] = entry["answered"] or message.status == "complete"
        entry["actions"].extend(a for a in (message.actions or []) if a.get("phase") == "finished")
    entries = sorted((e for e in entries if not e["pending"]), key=lambda e: e["at"])
    omitted = max(0, len(entries) - MAX_ENTRIES)
    entries = entries[-MAX_ENTRIES:]
    actions = [a for e in entries for a in e["actions"]]
    done = sum(1 for a in actions if a.get("status") == "succeeded")
    unconfirmed = sum(1 for a in actions if a.get("status") == "unverified")
    not_done = [a for a in actions if a.get("status") not in ("succeeded", "unverified")]
    conversations = len({e["conversation"] for e in entries})

    date = f"{now:%A} {now.day} {now:%B %Y}"
    lines = [f"Generated by NOVA at {now:%H:%M} from its stored conversations and action results.", "", "## Summary"]
    if not entries:
        lines.append("NOVA has no recorded requests for today.")
    else:
        lines += [f"- {len(entries)} request{'' if len(entries) == 1 else 's'} in {conversations} conversation"
                  f"{'' if conversations == 1 else 's'}",
                  f"- {len(actions)} action{'' if len(actions) == 1 else 's'} carried out by NOVA: {done} done, "
                  f"{unconfirmed} not confirmed, {len(not_done)} not done"]
        if omitted:
            lines.append(f"- The {omitted} earliest requests are not listed")
        lines += ["", "## Timeline", "| Time | Request | What NOVA did | Result |"]
        for e in entries:
            at = f"{e['at'].astimezone(now.tzinfo):%H:%M}"
            request = _cell(e["request"], 110)
            if not e["actions"]:
                lines.append(f"| {at} | {request} | Answered in the conversation | "
                             f"{'Answered' if e['answered'] else 'No answer recorded'} |")
            for index, a in enumerate(e["actions"]):
                lines.append(f"| {at if index == 0 else ''} | {request if index == 0 else ''} | {_describe(a)} | {_result(a)} |")
        if not_done or unconfirmed:
            lines += ["", "## Not completed"]
            lines += [f"- {_describe(a)}: {_result(a)}" for a in actions if a.get("status") != "succeeded"]
    return {"title": f"NOVA activity report, {date}", "date": f"{now:%Y-%m-%d}", "report": "\n".join(lines),
            "requests": len(entries), "actions": len(actions), "succeeded": done, "unconfirmed": unconfirmed,
            "not_done": len(not_done)}


def activity_tools(sessions: Callable[[], Any]) -> list[Tool]:
    """`sessions` opens a database session (a context manager), as `Database.SessionLocal` does."""

    def handler(_args: ToolInput, ctx: ToolContext) -> tuple[str, str, dict[str, Any]]:
        if ctx.owner_id is None:
            return "denied", "Activity records belong to a signed-in owner.", {"reason": "no_owner", "verified": False}
        with sessions() as db:
            found = today_activity(db, ctx.owner_id)
        message = (f"Found {found['requests']} request{'' if found['requests'] == 1 else 's'} and {found['actions']} "
                   f"action{'' if found['actions'] == 1 else 's'} in today's records.")
        return "succeeded", message, {"verified": True, **found}

    return [
        Tool("activity_today",
             "Read NOVA's own record of today: what the user asked and what NOVA actually did, with real results. Use "
             "it for 'what did we do today'; its report can be given to word_document as content.",
             ToolInput, PermissionLevel.READ, True, handler, timeout_s=10),
    ]
